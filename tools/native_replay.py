"""Compile finite JSON input traces into opt-in native replay C (no device I/O)."""
import argparse
import hashlib
import json
import math
from pathlib import Path

TYPES = {"action": 1, "pointer": 2, "control": 3, "imu": 4}
CONTROL_CODES = {"pause": 1, "resume": 2, "reset": 3}


def integer(value, name, minimum=0, maximum=0x7fffffff):
    if type(value) is not int or not minimum <= value <= maximum:
        raise ValueError(f"{name} must be an integer in [{minimum}, {maximum}]")
    return value


def boolean(value, name):
    if type(value) is not bool:
        raise ValueError(f"{name} must be a boolean")
    return value


def real(value, name):
    if type(value) not in (int, float) or abs(value) > 3.402823466e38 or not math.isfinite(value):
        raise ValueError(f"{name} must be a finite float32 number")
    return float(value)


def normalize(data, duration_ticks=None):
    if not isinstance(data, dict) or not isinstance(data.get("events"), list):
        raise ValueError("trace must be an object containing an events array")
    if "schema" in data and data["schema"] != "raylib-lite-native-replay-v1":
        raise ValueError("unsupported replay schema")
    embedded = data.get("duration_ticks")
    if duration_ticks is not None and embedded is not None and duration_ticks != embedded:
        raise ValueError("--ticks disagrees with duration_ticks")
    duration = integer(embedded if duration_ticks is None else duration_ticks,
                       "duration_ticks", 1, 0xffffffff)
    events = []
    for index, event in enumerate(data["events"]):
        if not isinstance(event, dict):
            raise ValueError(f"event {index} must be an object")
        if "frame" in event and "tick" in event:
            raise ValueError(f"event {index}: use frame or tick, not both")
        tick = integer(event.get("tick", event.get("frame")), f"event {index} tick", 0, duration - 1)
        kind = event.get("type")
        if isinstance(kind, str):
            kind = TYPES.get(kind.lower())
        if type(kind) is not int or kind not in TYPES.values():
            raise ValueError(f"event {index}: expected action/pointer/control/imu or numeric ABI type")
        row = {"tick": tick, "type": kind}
        if kind in (1, 3):
            code = event.get("code")
            if kind == 3 and isinstance(code, str):
                code = CONTROL_CODES.get(code.lower())
            row["code"] = integer(code, f"event {index} code", 1 if kind == 3 else 0,
                                  3 if kind == 3 else 0x7fffffff)
        if kind in (1, 2):
            row["pressed"] = boolean(event.get("pressed"), f"event {index} pressed")
        if kind == 2:
            row["track_id"] = integer(event.get("track_id", 0), f"event {index} track_id")
            for axis in ("x", "y"):
                row[axis] = integer(event.get(axis), f"event {index} {axis}", -0x80000000)
        if kind == 4:
            for axis in ("x", "y", "z"):
                row["value_" + axis] = real(event.get(axis), f"event {index} {axis}")
        events.append(row)
    # Stable sorting retains every press/release edge in author order at a tick.
    events.sort(key=lambda row: row["tick"])
    return {"duration_ticks": duration, "events": events}


def c_value(value):
    if type(value) is bool:
        return "true" if value else "false"
    if type(value) is float:
        text = format(value, ".9g")
        if "." not in text and "e" not in text:
            text += ".0"
        return text + "f"
    if value == -0x80000000:
        return "(-2147483647 - 1)"
    return str(value)


def generate(source, destination, duration_ticks=None):
    source = Path(source)
    raw = source.read_bytes()
    data = normalize(json.loads(raw), duration_ticks)
    canonical = json.dumps(data, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()
    source_hash = hashlib.sha256(raw).hexdigest()
    events_hash = hashlib.sha256(canonical).hexdigest()
    rows = []
    for event in data["events"]:
        fields = ", ".join(f".{name} = {c_value(value)}" for name, value in event.items() if name != "tick")
        rows.append(f"    {{{event['tick']}U, {{{fields}}}}},")
    if not rows:
        rows.append("    {0U, {0}}, /* Empty traces still have a valid C array. */")
    generated = '''// SPDX-License-Identifier: Apache-2.0
/* Generated by tools/native_replay.py. Do not hand-edit. */
#include "raylib_lite_native_replay.h"
#include "raylib_lite_raylib.h"

typedef struct { uint32_t tick; raylib_lite_game_input_v1_t input; } replay_event_t;
static const replay_event_t events[] = {
''' + "\n".join(rows) + '''
};
const raylib_lite_native_replay_info_t raylib_lite_native_replay_info = {
''' + f'''    {data['duration_ticks']}U, {len(data['events'])}U,
    "{source_hash}", "{events_hash}",
''' + '''};

bool raylib_lite_native_replay_tick(uint32_t tick,
    const raylib_lite_game_module_v1_t *module, void *state)
{
    static size_t next_event;
    if (tick == 0) next_event = 0;
    if (tick >= raylib_lite_native_replay_info.duration_ticks) return true;
    while (next_event < raylib_lite_native_replay_info.event_count && events[next_event].tick <= tick) {
        const replay_event_t *event = &events[next_event++];
        if (event->tick != tick) continue;
        const raylib_lite_game_input_v1_t *input = &event->input;
        if (input->type == RAYLIB_LITE_GAME_INPUT_ACTION)
            raylib_lite_raylib_inject_action(input->code, input->pressed);
        else if (input->type == RAYLIB_LITE_GAME_INPUT_POINTER)
            raylib_lite_raylib_inject_pointer(input->track_id, input->x, input->y, input->pressed);
        else if (input->type == RAYLIB_LITE_GAME_INPUT_IMU)
            raylib_lite_raylib_inject_imu(input->value_x, input->value_y, input->value_z);
        if (module && module->input) module->input(state, input);
    }
    return tick == raylib_lite_native_replay_info.duration_ticks - 1U;
}
'''
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(generated, encoding="utf-8")
    return {"schema": "raylib-lite-native-replay-v1", "duration_ticks": data["duration_ticks"],
            "event_count": len(data["events"]), "source_sha256": source_hash,
            "events_sha256": events_hash, "output": str(destination)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("trace", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--ticks", type=int, help="duration when the input trace omits duration_ticks")
    args = parser.parse_args()
    try:
        result = generate(args.trace, args.output, args.ticks)
    except (ValueError, KeyError, OSError) as error:
        parser.error(str(error))
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
