def check_shooter_view_coverage(repertoire: set[int], view_path: Path | None = None) -> set[int]:
    if view_path is None:
        view_path = ROOT.parent / "main/shooter_view.c"
    view_c = view_path.read_text(encoding="utf-8")
    required: set[int] = set(range(ord("0"), ord("9") + 1)) | {ord(" "), ord("?"), ord("-"), ord("/")}
    for literal in re.findall(r'"((?:[^"\\]|\\.)*)"', view_c):
        if any(ord(ch) >= 0x80 for ch in literal):
            cleaned = re.sub(r"%[0-9]*[a-zA-Z]+", "", literal)
            required.update(ord(ch) for ch in cleaned)
    missing = sorted(cp for cp in required if cp not in repertoire)
    if missing:
        formatted = ", ".join(f"U+{cp:04X} ({chr(cp)})" for cp in missing)
        raise ValueError(f"shooter_view.c uses glyphs missing from prepare_font.py: {formatted}")
    return required


def build_shooter_font(view_path: Path | None = None) -> None:
    all_codes = sorted(set(ASCII_GLYPHS) | set(CJK_GLYPHS))
    if view_path is not None:
        check_shooter_view_coverage(set(all_codes), view_path)
    cols, rows_cnt = 16, 4
    cell = 16
    atlas_w, atlas_h = cols * cell, rows_cnt * cell
    atlas = Image.new("RGBA", (atlas_w, atlas_h), (0, 0, 0, 0))
    px = atlas.load()
    entries = []
    for idx, cp in enumerate(all_codes):
        col, row = idx % cols, idx // cols
        cx, cy = col * cell + 2, row * cell + 2
        is_cjk = cp in CJK_GLYPHS
        gw = 12 if is_cjk else 8
        gh = 12
        adv = 14 if is_cjk else 9
        rows = CJK_GLYPHS[cp] if is_cjk else ASCII_GLYPHS[cp]
        bit_w = 12 if is_cjk else 8
        for ry, row_bits in enumerate(rows):
            for rx in range(bit_w):
                if row_bits & (1 << (bit_w - 1 - rx)):
                    px[cx + rx, cy + ry] = (255, 255, 255, 255)
        entries.append((cp, cx, cy, gw, gh, 0, 2, adv))

    atlas.save(ROOT / "shooter_zh_source.png", optimize=True)
    config = {
        "image": "shooter_zh_source.png",
        "columns": cols,
        "rows": rows_cnt,
        "output_cell": cell,
        "output_columns": cols,
        "alpha_mode": "binary",
        "padding": 0,
        "frames": [{"name": f"zh_cell_{i}", "source_index": i} for i in range(cols * rows_cnt)],
    }
    (ROOT / "shooter_zh.json").write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    lines = [
        'info face="MosaicoPixel" size=16',
        f"common lineHeight=16 base=13 scaleW={atlas_w} scaleH={atlas_h} pages=1",
        'page id=0 file="shooter_zh.png"',
        f"chars count={len(entries)}",
    ]
    for cp, gx, gy, gw, gh, ox, oy, adv in entries:
        lines.append(
            f"char id={cp} x={gx} y={gy} width={gw} height={gh} "
            f"xoffset={ox} yoffset={oy} xadvance={adv} page=0"
        )
    (ROOT / "shooter_zh.fnt").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    build_shooter_font()
